"""Thin Sabre domain/state projection for isolated integration-v0."""
from __future__ import annotations

from collections import deque
from pathlib import Path

HORIZON = 24
ROOMS = ("junction", "side_passage", "inn")
ALIASES = {"junction": "Junction", "side_passage": "SidePassage", "inn": "Inn"}


def _check_snapshot(s: dict) -> None:
    if s.get("schema") != "planner-p0-integration-v0":
        raise ValueError("not a planner-p0-integration-v0 snapshot")
    clock = s.get("clock", {})
    if clock.get("unit") != "minute" or clock.get("deadline") != HORIZON:
        raise ValueError("integration-v0 uses the fixed 24-minute horizon")
    if type(clock.get("now")) is not int or not 0 <= clock["now"] <= HORIZON:
        raise ValueError("snapshot minute is outside the registered horizon")
    if s.get("mode") not in {"free", "conditional", "direct"}:
        raise ValueError("unknown control mode")
    if set(s.get("actors", {})) != {"A", "B", "player"}:
        raise ValueError("snapshot must contain exactly A, B, and player")
    if set(s.get("rooms", {})) != set(ROOMS):
        raise ValueError("snapshot room aliases do not match integration-v0")


def _delivery_costs(s: dict) -> dict[str, int | None]:
    """Exact forecast primitive count, by A's possible starting room.

    Uses authoritative physical route/holder state to price the abstract task;
    the primitive action sequence is still generated by P3 GTPyhop from A's
    local view and individually settled in the native world.
    """
    rooms = s["rooms"]
    graph = {rid: [] for rid in rooms.values()}
    for route in s["routes"]:
        for edge in route["edges"]:
            if edge.get("traversable"):
                graph[rooms[edge["from"]]].append(rooms[edge["to"]])

    def distance(start, target):
        queue, seen = deque([(start, 0)]), {start}
        while queue:
            room, n = queue.popleft()
            if room == target:
                return n
            for nxt in graph.get(room, ()):
                if nxt not in seen:
                    seen.add(nxt); queue.append((nxt, n + 1))
        return None

    item = s["items"]["shelter_kit"]
    inn = rooms["inn"]
    if item.get("holder_role") == "A":
        return {name: (distance(rooms[name], inn) + 1
                       if distance(rooms[name], inn) is not None else None) for name in ROOMS}
    # This location is the actor's stored local knowledge, not the W item location.
    item_room = (s["actors"]["A"].get("local_view", {}).get("observation", {})
                 .get("item_location"))
    if item_room is None:
        return {name: None for name in ROOMS}
    final_leg = distance(item_room, inn)
    result = {}
    for name in ROOMS:
        first_leg = distance(rooms[name], item_room)
        result[name] = (None if first_leg is None or final_leg is None
                        else first_leg + 1 + final_leg + 1)  # GET and DROP
    return result


def render_problem(snapshot: dict, *, task_offer_predicted: bool = False,
                   meeting_witness: bool = False) -> str:
    """Render the live snapshot using numeric Sabre time fluents.

    A macro duration is a forecast, not a native receipt. `meeting_witness`
    may only be supplied after the caller verifies the committed witness row.
    """
    _check_snapshot(snapshot)
    now, mode = snapshot["clock"]["now"], snapshot["mode"]
    actors, room_ids = snapshot["actors"], snapshot["rooms"]
    room_name = {room_ids[k]: ALIASES[k] for k in ROOMS}
    authorized = mode in {"conditional", "direct"}
    offerable = mode == "conditional" and actors["A"].get("own_goal") == "deliver_shelter"
    task = actors["A"].get("active_task")
    task_active = bool(task and task.get("status") in {"accepted", "active", "blocked", "settled"})
    delivered = bool(task and task.get("status") == "settled")
    costs = {} if delivered else _delivery_costs(snapshot)
    lines = [
        "type character : location;", "type place : location;", "type weather;",
        "entity A : character;", "entity B : character;",
        "entity Clear : weather;", "entity Storm : weather;",
        *(f"entity {ALIASES[r]} : place;" for r in ROOMS), "",
        "property at(character : character) : place;",
        "property now() : number;", "property weather() : weather;",
        "property path(from : place, to : place) : boolean;",
        "property knows_storm(character : character) : boolean;",
        "property kit_held(character : character) : boolean;",
        "property shelter_delivered() : boolean;", "property task_bound() : boolean;",
        "property met_witness() : boolean;",
        "property offerable() : boolean;", "property author_actions_allowed() : boolean;",
        "property character_actions_allowed() : boolean;",
        "property direct_control_allowed() : boolean;",
        "property delivery_feasible(source : place) : boolean;",
        "property pending_cloud() : boolean;", "property cloud_due() : number;",
        "property delivery_cost(source : place) : number;", "",
        f"now() = {now};",
        f"weather() = {'Storm' if snapshot['weather'] == 'storm' else 'Clear'};",
    ]
    for r in ROOMS:
        duration = costs.get(r)
        if duration is not None and duration > 0:
            lines.extend([f"delivery_cost({ALIASES[r]}) = {duration};",
                          f"delivery_feasible({ALIASES[r]});"])
    for role in ("A", "B"):
        actor = actors[role]
        rid = actor.get("room_id")
        if rid not in room_name:
            raise ValueError(f"{role} is not located in a registered room")
        lines.append(f"at({role}) = {room_name[rid]};")
        if "storm" in actor.get("known_weather", []):
            lines.append(f"knows_storm({role});")
    holder = snapshot["items"]["shelter_kit"].get("holder_role")
    if holder in {"A", "B"}:
        lines.append(f"kit_held({holder});")
    if task_active:
        lines.append("task_bound();")
    if delivered:
        lines.append("shelter_delivered();")
    if offerable or task_offer_predicted:
        lines.append("offerable();")
    if authorized:
        lines.extend(["author_actions_allowed();", "character_actions_allowed();"])
    if mode == "direct":
        lines.append("direct_control_allowed();")
    if meeting_witness:
        lines.append("met_witness();")
    pending = snapshot.get("pending_cloud")
    if pending:
        due = pending.get("due_at")
        if type(due) is int and now <= due <= HORIZON:
            lines.extend(["pending_cloud();", f"cloud_due() = {due};"])
    for route in snapshot["routes"]:
        for edge in route["edges"]:
            if edge.get("traversable"):
                lines.append(f"path({ALIASES[edge['from']]}, {ALIASES[edge['to']]});")
    lines.extend([
        "", "trigger storm_arrives() {", "\tprecondition:",
        "\t\tpending_cloud() & now() >= cloud_due() & weather() == Clear;",
        "\teffect: weather() = Storm & !pending_cloud();", "};", "",
        "action wait(actor : character) {", "\tprecondition: character_actions_allowed() & now() < 24;",
        "\teffect: now() = now() + 1;",
        *( ["\tconsenting: actor;"] if mode == "conditional" else [] ), "};", "",
        "action look(actor : character) {", "\tprecondition: character_actions_allowed() & now() < 24;",
        "\teffect: if(weather() == Storm) knows_storm(actor) & now() = now() + 1 else now() = now() + 1;",
        *( ["\tconsenting: actor;"] if mode == "conditional" else [] ), "};", "",
        "action move(actor : character, source : place, destination : place) {",
        "\tprecondition: character_actions_allowed() & at(actor) == source & path(source, destination) & now() < 24;",
        "\teffect: at(actor) = destination & now() = now() + 1;",
        *( ["\tconsenting: actor;"] if mode == "conditional" else [] ), "};", "",
        "action cloud_seed() {", "\tprecondition:",
        "\t\tauthor_actions_allowed() & weather() == Clear & now() <= 22;",
        "\teffect: pending_cloud() & cloud_due() = now() + 2 & now() = now() + 1;", "};", "",
        "action offer_task() {", "\tprecondition:",
        "\t\tauthor_actions_allowed() & offerable() & !task_bound() & now() < 24;",
        "\teffect: task_bound() & now() = now() + 1;", "};", "",
        "action dispatch_task() {", "\tprecondition:",
        "\t\tauthor_actions_allowed() & direct_control_allowed() & !task_bound() & now() < 24;",
        "\teffect: task_bound() & now() = now() + 1;", "};", "",
        # The only compound action. Its numeric cost is tied to the real current
        # topology; its P3 refinement is executed as distinct native primitives.
        "action deliver_shelter(source : place) {", "\tprecondition:",
        "\t\tcharacter_actions_allowed() & delivery_feasible(source) & at(A) == source & task_bound() & !shelter_delivered() & now() + delivery_cost(source) <= 24;",
        "\teffect: shelter_delivered() & at(A) = Inn & now() = now() + delivery_cost(source);", "};", "",
        "action meet() {", "\tprecondition:",
        "\t\tcharacter_actions_allowed() & at(A) == Inn & at(B) == Inn & now() < 24;",
        "\teffect: if(weather() == Storm & knows_storm(B) & shelter_delivered()) met_witness() & now() = now() + 1 else now() = now() + 1;",
        *( ["\tconsenting: A, B;"] if mode == "conditional" else [] ), "};", "",
        "utility(): if(met_witness() & weather() == Storm & knows_storm(B) & shelter_delivered()) 1 else 0;",
        "utility(A): if(shelter_delivered() & met_witness()) 2 elseif(shelter_delivered()) 1 else 0;",
        "utility(B): if(met_witness() & knows_storm(B)) 2 elseif(knows_storm(B)) 1 else 0;", "",
        "/* Hand-authored finite fixture domain; not a complete traditional planner.",
        "   `delivery_cost` is an exact forecast, not a receipt. Sabre action choice",
        "   is separate from the existing P3 GTPyhop macro refinement and native",
        "   settlement. The native clock/weather ledger is authoritative. */",
    ])
    return "\n".join(lines) + "\n"


def export_problem(snapshot: dict, destination: str | Path, *, task_offer_predicted=False,
                   meeting_witness=False) -> Path:
    out = Path(destination)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_problem(snapshot, task_offer_predicted=task_offer_predicted,
                                  meeting_witness=meeting_witness), encoding="utf-8")
    return out
